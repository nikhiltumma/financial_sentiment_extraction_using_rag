"""
Build (or rebuild) the FAISS index from knowledge graphs.

Usage:
  cd backend
  python scripts/build_faiss_index.py

Requires:
  - Knowledge graphs in backend/knowledge_graphs/*.json (generated by
    POST /graph/generate which calls Gemini)
  - faiss-cpu + sentence-transformers installed

The index is saved to backend/vector_store/ and auto-loaded by
KGRetriever at runtime.
"""

from __future__ import annotations

import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND_DIR))

from app.services.kg_retriever import KGRetriever


def main() -> None:
    print("Building FAISS index from knowledge graphs...")
    retriever = KGRetriever()

    try:
        result = retriever.build_index()
    except FileNotFoundError as exc:
        print(f"ERROR: {exc}")
        print("Generate knowledge graphs first via POST /graph/generate")
        print("  curl -X POST http://localhost:8000/graph/generate ...")
        sys.exit(1)

    print(f"Status: {result['status']}")
    print(f"Evidence count: {result['evidence_count']}")
    print(f"Embedding dimension: {result['embedding_dimension']}")
    print(f"Index type: {result['index_type']}")
    print(f"Saved to: {BACKEND_DIR / 'vector_store'}")


if __name__ == "__main__":
    main()
